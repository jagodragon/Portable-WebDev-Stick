<?php
// ============================================================================
//  Portable WebDev Stick - setup file generator (SHARED)
//  Installs to:  SharedSettings/setup-generate.php
//
//  Called once by 1stRun.Setup.sh / 1stRun.Setup.bat. The calling script has
//  already collected the secrets with no-echo prompts and passes them through
//  environment variables - they are never stored in any file by hand.
//  This generator writes exactly two files:
//
//    1. A one-time SQL file (the caller's temp copy of setup.sql with the
//       password tokens replaced). The caller deletes it right after use.
//    2. SharedSettings/db-credentials.php - the permanent credentials file
//       that the database editor wrapper and your own projects include.
//
//  Environment variables read:
//    SETUP_ROOT_PW, SETUP_WEBDEV_PW, SETUP_GATE_USER, SETUP_GATE_PW,
//    SETUP_EDITOR_DB, SETUP_SQL_TEMPLATE, SETUP_TMP_SQL, SETUP_CREDS_FILE
// ============================================================================

function env_req(string $name): string {
    $v = getenv($name);
    if ($v === false || $v === '') {
        fwrite(STDERR, "setup-generate: missing environment value $name\n");
        exit(1);
    }
    return $v;
}

function sql_literal(string $s): string {
    // MariaDB string-literal escaping (default SQL mode):
    // backslashes first, then single quotes.
    return str_replace(['\\', "'"], ['\\\\', "\\'"], $s);
}

$rootPw   = env_req('SETUP_ROOT_PW');
$webdevPw = env_req('SETUP_WEBDEV_PW');
$gateUser = env_req('SETUP_GATE_USER');
$gatePw   = env_req('SETUP_GATE_PW');
$editorDb = env_req('SETUP_EDITOR_DB');
$template = env_req('SETUP_SQL_TEMPLATE');
$tmpSql   = env_req('SETUP_TMP_SQL');
$credsOut = env_req('SETUP_CREDS_FILE');

// The editor database name becomes part of the SQL as an identifier, so it is
// restricted to plain letters, digits and underscores - no escaping tricks.
if (!preg_match('/^[A-Za-z0-9_]+$/', $editorDb)) {
    fwrite(STDERR, "setup-generate: database name '$editorDb' may only contain letters, digits and underscores\n");
    exit(1);
}

// ---- File 1: the one-time SQL ---------------------------------------------
$tpl = file_get_contents($template);
if ($tpl === false) {
    fwrite(STDERR, "setup-generate: cannot read template $template\n");
    exit(1);
}
$sql = str_replace(
    ['__ROOT_PW__', '__WEBDEV_PW__', '__EDITOR_DB__'],
    [sql_literal($rootPw), sql_literal($webdevPw), $editorDb],
    $tpl
);
if (strpos($sql, '__ROOT_PW__') !== false
    || strpos($sql, '__WEBDEV_PW__') !== false
    || strpos($sql, '__EDITOR_DB__') !== false) {
    fwrite(STDERR, "setup-generate: template tokens were not all replaced\n");
    exit(1);
}
if (file_put_contents($tmpSql, $sql) === false) {
    fwrite(STDERR, "setup-generate: cannot write $tmpSql\n");
    exit(1);
}

// ---- File 2: the permanent credentials file --------------------------------
// The webdev password is stored readable: programs must be able to present
// it to MariaDB. The editor gate password is stored ONLY as a hash: it is
// verified, never presented, so it never needs to exist in plain text.
$creds = [
    'db' => [
        'host' => '127.0.0.1',
        'port' => 3306,
        'user' => 'webdev',
        'pass' => $webdevPw,
    ],
    'editor' => [
        'user'          => $gateUser,
        'pass_hash'     => password_hash($gatePw, PASSWORD_DEFAULT),
        'database'      => $editorDb,
        'permanent_key' => bin2hex(random_bytes(16)),
    ],
];
$php = "<?php\n"
    . "// Portable WebDev Stick - generated by 1stRun.Setup. Do not share or commit this file.\n"
    . "// It holds this stick's webdev database password (your projects include this file\n"
    . "// to connect) and the database editor's settings. Re-running 1stRun.Setup after\n"
    . "// deleting SharedFolders/data/.setup-done regenerates it.\n"
    . "return " . var_export($creds, true) . ";\n";
if (file_put_contents($credsOut, $php) === false) {
    fwrite(STDERR, "setup-generate: cannot write $credsOut\n");
    exit(1);
}
