#!/usr/bin/env bash
# a.Ports.FixConflicts.sh - the port decider (Linux).
#
# What it does:
#   For every service in the stack, it tests the default port declared in
#   SharedSettings/Ports.Default.conf. A port that is free is kept. A port
#   that is already in use is replaced by the first free port in that
#   service's [DefaultRanges] span. The decided set is written to
#   SharedSettings/Ports.InUse.conf, and from then on every start/stop
#   script uses those ports automatically.
#
#   The decision is all-or-nothing: if any service has no free port in its
#   range, nothing is written and the previous state is kept.
#
# Run it while the stack is STOPPED. The decider refuses to run while a
# stack server is alive: it would mistake the stack's own ports for
# conflicts, and the stop scripts must always be able to find the servers
# they started.
#
# To undo a decision, run a.Ports.UseDefaults (it deletes Ports.InUse.conf).
#
# Lives in OS_Linux/Scripts; the double-click entry point is
# a.Ports.FixConflicts.desktop at the stick root.

# This worker lives in OS_Linux/Scripts; the stick root is two levels up.
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
USB_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
SETTINGS="$USB_ROOT/SharedSettings"
DEFAULTS="$SETTINGS/Ports.Default.conf"
INUSE="$SETTINGS/Ports.InUse.conf"
DATA_DIR="$USB_ROOT/SharedFolders/data"

say()  { printf '%s\n' "$*"; }
fail() { printf '*** %s\n' "$*" >&2; pause_at_end; exit 1; }
pause_at_end() {
    if [ -t 0 ]; then printf 'Press Enter to close... '; read -r _ || true; fi
}

# Read KEY from [SECTION] of a conf file. Prints the value, or nothing.
conf_get() {
    awk -v sec="[$2]" -v key="$3" '
        { sub(/\r$/, "") }
        /^\[/ { insec = ($0 == sec); next }
        insec && $0 ~ "^[ \t]*" key "[ \t]*=" {
            line = $0
            sub(/^[^=]*=/, "", line)
            sub(/[;#].*$/, "", line)
            gsub(/[ \t]/, "", line)
            print line; exit
        }' "$1" 2>/dev/null
}

# Is anything listening on 127.0.0.1:$1 ?
port_taken() { (exec 3<>"/dev/tcp/127.0.0.1/$1") 2>/dev/null; }

# ---- Preflight ---------------------------------------------------------------
[ -f "$DEFAULTS" ] || fail "Ports.Default.conf not found in SharedSettings - is this script at the stick root?"

if [ -d "$DATA_DIR" ]; then
    shopt -s nullglob
    for pidfile in "$DATA_DIR"/*.pid; do
        pid="$(tr -dc '0-9' < "$pidfile")"
        if [ -n "$pid" ] && kill -0 "$pid" 2>/dev/null; then
            fail "a stack server is still running (pid $pid). Stop the stack first - ports are decided while the stack is down."
        fi
    done
    shopt -u nullglob
fi

# ---- Decide ------------------------------------------------------------------
KEYS="WEB MARIADB REDIS FPM NODE"
declare -A BUILTIN_PORT=( [WEB]=8080 [MARIADB]=3306 [REDIS]=6379 [FPM]=9000 [NODE]=3000 )
declare -A BUILTIN_RANGE=( [WEB]=8080-8084 [MARIADB]=3306-3310 [REDIS]=6379-6383 [FPM]=9000-9004 [NODE]=3000-3004 )
declare -A RESULT=() NOTE=() USED=()

for key in $KEYS; do
    def="$(conf_get "$DEFAULTS" DefaultPorts "$key")"
    if ! [[ "$def" =~ ^[0-9]+$ ]]; then
        say "Warning: no usable $key entry in [DefaultPorts]; using the built-in default ${BUILTIN_PORT[$key]}."
        def="${BUILTIN_PORT[$key]}"
    fi
    if ! port_taken "$def" && [ -z "${USED[$def]:-}" ]; then
        RESULT[$key]="$def"; NOTE[$key]="default"; USED[$def]="$key"; continue
    fi
    range="$(conf_get "$DEFAULTS" DefaultRanges "$key")"
    [[ "$range" =~ ^[0-9]+-[0-9]+$ ]] || range="${BUILTIN_RANGE[$key]}"
    lo="${range%-*}"; hi="${range#*-}"
    found=""
    for (( p = lo; p <= hi; p++ )); do
        [ -n "${USED[$p]:-}" ] && continue
        if ! port_taken "$p"; then found="$p"; break; fi
    done
    [ -n "$found" ] || fail "no free port for $key in range $range. Free a port, or widen the range in Ports.Default.conf. Nothing was written."
    RESULT[$key]="$found"; NOTE[$key]="$def was in use"; USED[$found]="$key"
done

# ---- Write (all-or-nothing, atomic replace) -----------------------------------
tmp="$INUSE.tmp.$$"
{
    say "# Ports.InUse.conf - generated by a.Ports.FixConflicts; do not hand-edit."
    say "# Run a.Ports.UseDefaults to delete this file and return to Ports.Default.conf."
    say "SESSION=$(date '+%Y-%m-%d %H:%M') on $(hostname)"
    say ""
    say "[InUsePorts]"
    for key in $KEYS; do say "$key=${RESULT[$key]}"; done
} > "$tmp" || fail "could not write to SharedSettings."
mv -f "$tmp" "$INUSE" || fail "could not replace Ports.InUse.conf."

say "Ports decided:"
for key in $KEYS; do
    if [ "${NOTE[$key]}" = "default" ]; then
        say "  $key = ${RESULT[$key]}  (default, free)"
    else
        say "  $key = ${RESULT[$key]}  (${NOTE[$key]})"
    fi
done
say ""
say "Written to SharedSettings/Ports.InUse.conf. Start the stack the normal"
say "way - the launchers read the decided ports from that file."
pause_at_end
